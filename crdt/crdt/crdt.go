func (downOp MultiUpd) FromReplicatorObj(protobuf *proto.ProtoOpDownstream) (downArgs DownstreamArguments) {
	multiProto := protobuf.GetMultiUpdOp()
	protoUpds, crdtType := multiProto.GetUpdates(), multiProto.GetType()
	downOp = make(MultiUpd, len(protoUpds))
	for i, inUpd := range protoUpds {
		downOp[i] = DownstreamProtoToAntidoteDownstream(inUpd, crdtType)
		if downOp[i] == nil {
			fmt.Printf("[MultiUpd][FromUpdateObject]Error converting downstream inner proto upds to antidote update: got nil. Original upd, CRDT type: %v, %v.\n", inUpd, crdtType)
			os.Exit(0)
		}
	}
	return downOp
}

func (downOp MultiUpd) ToReplicatorObj() (protobuf *proto.ProtoOpDownstream) {
	protoSlice := make([]*proto.ProtoOpDownstream, len(downOp))
	for i, inUpd := range downOp {
		protoSlice[i] = inUpd.(ProtoDownUpd).ToReplicatorObj()
		if protoSlice[i] == nil {
			fmt.Printf("[MultiUpd][ToUpdateObject]Error converting downstream inner antidote upds to proto update: got nil. Original upd, type: %v, %T.\n", inUpd, inUpd)
			os.Exit(0)
		}
	}
	return &proto.ProtoOpDownstream{Specialop: proto.SPECIAL_UPD_MULTI.Enum(), Op: &proto.ProtoOpDownstream_MultiUpdOp{MultiUpdOp: &proto.ProtoMultiUpdateDownstream{Updates: protoSlice, Type: downOp.GetCRDTType().Enum()}}}
}

