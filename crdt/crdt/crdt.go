// Similar to createPartialRead from antidoteProtoLib.go
func ReadObjectParamsToPartialRead(readParams ReadObjectParams) (protobuf *proto.ApbPartialRead) {
	readType := readParams.ReadArgs.GetREADType()
	protobuf = &proto.ApbPartialRead{Object: createBoundObject(readParams.Key, readParams.CrdtType, readParams.Bucket), Readtype: &readType}
	if readType == proto.READType_FULL {
		protobuf.Args = &proto.ApbPartialReadArgs{}
	} else {
		protobuf.Args = readParams.ReadArgs.(ProtoRead).ToPartialRead()
	}
	return
}

func initializeDummyCRDTs() []CRDT {
	var dummyCRDTs []CRDT
	crdtTypeToName := proto.CRDTType_name
	crdtKeys := make([]proto.CRDTType, len(crdtTypeToName))
	i := 0
	for crdtType := range crdtTypeToName {
		crdtKeys[i] = proto.CRDTType(crdtType)
		i++
	}
	//Sort the keys to ensure the same order every time
	sort.Slice(crdtKeys, func(i, j int) bool { return crdtKeys[i] < crdtKeys[j] })
	dummyCRDTs = make([]CRDT, crdtKeys[len(crdtKeys)-1]+1) //This way, even if the CRDT type is higher than the number of types, we have space for it.
	for _, crdtType := range crdtKeys {
		dummyCRDTs[crdtType] = InitializeCrdt(crdtType, proto.DATAType_INT, 0) //Non-generic CRDTs will ignore the DATAType field.
	}
	return dummyCRDTs
}

