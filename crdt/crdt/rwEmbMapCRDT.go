func (crdt *RWEmbMapCrdt) undoUpdateSingleEffect(updated string, previousRmvClk markedVC, addedMark bool, replicaID uint16) {
	if previousRmvClk != nil {
		crdt.removes[updated] = previousRmvClk //Safe since this is a CRDT copy that won't be changed
		crdt.entries.Delete(updated)
	}
	if addedMark {
		crdt.removes[updated].unmark(int(replicaID))
	}
	crdt.keysToRebuild[updated] = struct{}{}
}

func (crdt *RWEmbMapCrdt) undoRemoveAllEffect(removedCRDTs map[string]CRDT, replicaID uint16, previousClk int64) {
	//CRDTs that were removed by this remove. We need to add them back
	for key, embCrdt := range removedCRDTs {
		crdt.entries.Set(key, embCrdt)
		delete(crdt.removes, key)
	}
	crdt.rmvClock.UpdateForcedPos(replicaID, previousClk)
}

func (crdt *RWEmbMapCrdt) undoRemoveSingleEffect(removedKey string, removedCRDT CRDT, previousRmvClk int64, replicaID uint16) {
	if removedCRDT != nil {
		crdt.entries.Set(removedKey, removedCRDT)
		delete(crdt.removes, removedKey)
	}
	crdt.rmvClock.UpdateForcedPos(replicaID, previousRmvClk)
}

func (crdt *RWEmbMapCrdt) notifyRebuiltComplete(currTs clocksi.Timestamp) {
	//Only redo CRDTs that were altered
	for key := range crdt.keysToRebuild {
		crdt.entries.GetDirect(key).(InversibleCRDT).RebuildCRDTToVersion(currTs)
	}
	crdt.keysToRebuild = nil
}

