// Intended for big updates, it uses goroutines to parallelize the conversion
func FromProtoEmbMapUpdToKeyDownArgsPairSlice(upds []*proto.ProtoEmbMapUpd) (pairs []KeyDownArgsPair) {
	pairs = make([]KeyDownArgsPair, len(upds))
	nParts := min(len(upds)/20000, 32)
	nFactor := len(upds) / nParts
	var wg sync.WaitGroup
	wg.Add(nParts)
	for i := 0; i < nParts; i++ {
		go func(start, end int) {
			var upd *proto.ProtoEmbMapUpd
			for ; start < end; start++ {
				upd = upds[start]
				pairs[start] = KeyDownArgsPair{Key: tools.UnsafeBytesToString(upd.GetKey()), Upd: DownstreamProtoToAntidoteDownstream(upd.GetUpd(), upd.GetType())}
			}
			wg.Done()
		}(i*nFactor, (i+1)*nFactor)
	}
	var upd *proto.ProtoEmbMapUpd
	for k := nFactor * nParts; k < len(upds); k++ {
		upd = upds[k]
		pairs[k] = KeyDownArgsPair{Key: tools.UnsafeBytesToString(upd.GetKey()), Upd: DownstreamProtoToAntidoteDownstream(upd.GetUpd(), upd.GetType())}
	}
	wg.Wait()
	return pairs
}

