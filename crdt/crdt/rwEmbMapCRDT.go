func (crdt *RWEmbMapCrdt) getNShardsForNewMap(desiredSize int) (nShards int) {
	if desiredSize <= RWEMBMAP_MIN_SIZE_FOR_SHARDING { //300k
		return 1
	}
	if desiredSize < 1000000 { //1M
		return desiredSize/100000 + 1 //4-10 shards. We avoid 2 and 3 shards as then the overhead of having a slice is not worth it (more cache misses with little benefit).
	}
	if desiredSize < 10000000 { //10M
		return 10 + desiredSize/500000 //12-30 shards.
	}
	return 21 + desiredSize/1000000 //31+ shards. 21 shards + (10M/1M) = 10 + ((desiredSize-10M)/1M).
}

