func (crdt *RWEmbMapCrdt) aggregateProcessState(currState State, aggrType AggregateType, aggrKey string, cResult float64, cCount int) (result float64, count int) {
	if currState == nil { //May happens as, e.g., a conditional read was applied and conditions were not meet, thus generating an empty state.
		return 0, 1
	}
	aggrState, ok := currState.(AggregateState)
	if !ok {
		fmt.Printf("[RWEmbMap][aggregateProcessState]State is not an AggregateState: %T\n", currState)
	}
	result, count = aggrState.GetAggregateResult(aggrType, aggrKey)
	return result + cResult, count + cCount
}

