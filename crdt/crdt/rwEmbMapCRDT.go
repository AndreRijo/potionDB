func compareArgsToProtoHelper(key string, args CompareArguments, protobuf *proto.ApbMapCondArgs) {
	if key != "" {
		protobuf.Key = pb.String(key)
	}
	var compType proto.COMPType
	//Missing the CompareArguments with the variables?
	switch typedArgs := args.(type) {
	case IntCompareArguments:
		compType = proto.COMPType(typedArgs.CompType)
		protobuf.Comp = &proto.ApbMapCondArgs_Intcomp{Intcomp: &proto.ApbCondIntCompare{Value: pb.Int64(typedArgs.Value), Comp: &compType}}
	case FloatCompareArguments:
		compType = proto.COMPType(typedArgs.CompType)
		protobuf.Comp = &proto.ApbMapCondArgs_Floatcomp{Floatcomp: &proto.ApbCondFloatCompare{Value: pb.Float64(typedArgs.Value), Comp: &compType}}
	case MapCompareArguments:
		mapComp := &proto.ApbCondMapCompare{Value: make([]*proto.ApbMapCondArgs, len(typedArgs.MapArgs))}
		i := 0
		for key, args := range typedArgs.MapArgs {
			mapComp.Value[i] = &proto.ApbMapCondArgs{}
			compareArgsToProtoHelper(key, args, mapComp.Value[i])
			i++
		}
		protobuf.Comp = &proto.ApbMapCondArgs_Mapcomp{Mapcomp: mapComp}
	case BoolCompareArguments:
		protobuf.Comp = &proto.ApbMapCondArgs_Boolcomp{Boolcomp: &proto.ApbCondBoolCompare{Value: pb.Bool(typedArgs.Value), IsEqualComp: &typedArgs.IsEqualComp}}
	case StringCompareArguments:
		protobuf.Comp = &proto.ApbMapCondArgs_Stringcomp{Stringcomp: &proto.ApbCondStringCompare{Value: pb.String(typedArgs.Value), IsEqualComp: &typedArgs.IsEqualComp}}
	case BytesCompareArguments:
		protobuf.Comp = &proto.ApbMapCondArgs_Bytescomp{Bytescomp: &proto.ApbCondBytesCompare{Value: typedArgs.Value, IsEqualComp: &typedArgs.IsEqualComp}}
	case GetNoCompareArguments:
		protobuf.Comp = &proto.ApbMapCondArgs_Nocomp{Nocomp: &proto.ApbCondGetNoCompare{}}
	}
}

