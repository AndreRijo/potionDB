func (crdt *RWEmbMapCrdt) applyUpdateSingle(updTs clocksi.Timestamp, key string, upd DownstreamArguments,
	remClks []int64, remoteID uint16, isRedo bool) (effect Effect, otherDownstreamArgs DownstreamArguments) {

	effect = NoOp{}
	//No need to check if it exists in removes, which is the more likely scenario.
	if len(crdt.removes) == 0 {
		effect = &RWEmbMapUpdateSingleEffect{Updated: key, ReplicaID: remoteID}
		if !isRedo {
			embCRDT, new := crdt.getOrCreateEmbCrdt(key, upd)
			embDownstream := embCRDT.Downstream(updTs, upd)
			if new {
				crdt.entries.Set(key, embCRDT)
			}
			if embDownstream != nil {
				otherDownstreamArgs = DownstreamRWEmbMapUpdateSingle{Key: key, Upd: embDownstream, ReplicaID: crdt.replicaID}
			}
		}
	} else {
		keyRemClk, has := crdt.removes[key]
		canAdd := !has
		if has { //Remove-wins policy, this add can only have effect if it surparsses all removes.
			canAdd = keyRemClk.isLowerThan(remClks) //remClks must be >= in all positions for the add to be applicable.
			if canAdd {                             //Safe to add, as this add is after the remove. We need to add the mark
				keyRemClk.setMark(int(remoteID))
				effect = &RWEmbMapUpdateSingleEffect{Updated: key, AddedMark: true, ReplicaID: remoteID}
				if keyRemClk.isAllMarked() {
					effect.(*RWEmbMapUpdateSingleEffect).PreviousRmvClk = keyRemClk
					delete(crdt.removes, key)
				}
			}
		} else if !has {
			effect = &RWEmbMapUpdateSingleEffect{Updated: key, ReplicaID: remoteID}
		}
		if canAdd { //Actually applying the add
			if !isRedo { //Only apply the upd if it isn't a redo (since if it's a redo, we'll just ask the embedded CRDT to rebuild itself by the end)
				embCRDT, new := crdt.getOrCreateEmbCrdt(key, upd)
				embDownstream := embCRDT.Downstream(updTs, upd)
				if new {
					crdt.entries.Set(key, embCRDT)
				}
				if embDownstream != nil {
					otherDownstreamArgs = DownstreamRWEmbMapUpdateSingle{Key: key, Upd: embDownstream, ReplicaID: crdt.replicaID}
				}
			}
		}
	}
	return effect, otherDownstreamArgs
}

