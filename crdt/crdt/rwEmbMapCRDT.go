// First update is intended for initializing big maps (millions of CRDTs), where efficiency is key.
// For efficiency reasons, we separate this in two downstreams: one for local, one for remote.
// Local one uses EmbMapUpdate, so that when splitting the updates through different goroutines, each goroutine can do both Update() and Downstream().
// This also saves an extra array conversion (i.e., allocating an extra array and filling it up) from update to downstream.
// However, for replication to work later, local will modify upds during downstream, replacing the Update versions with Downstream versions.
// This is still better than copying an array as it is done while preparing the updates with multiple goroutines,
// so we hide the cost of copying the array under the cost of populating the map.
// Remote one uses KeyDownArgsPair, as when we receive the remote operation, we only have the downstreamed version.
// Remote one only applies downstream, instead of both.
type LocalDownstreamRWEmbMapFirstUpdate struct {
	Upds      []EmbMapUpdate
	ReplicaID uint16
}

// Remote version of DownstreamRWEmbMapFirstUpdate. Check comments of LocalDownstreamRWEmbMapFirstUpdate
type RemoteDownstreamRWEmbMapFirstUpdate struct {
	Upds      []KeyDownArgsPair
	ReplicaID uint16
}

type KeyDownArgsPair struct {
	Key string
	Upd DownstreamArguments
}

