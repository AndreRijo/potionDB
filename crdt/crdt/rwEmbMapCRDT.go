// To avoid code repetition, this helper tries to find the state inside a map
func aggregateProcessStateHelper(currState State, aggregateType AggregateType) (valueCounter float64, valueCount int) {
	switch typedState := currState.(type) {
	case CounterState:
		return float64(typedState), 1
	case CounterFloatState:
		return float64(typedState), 1
	case CounterArraySingleState:
		return float64(typedState), 1
	case AvgFullState:
		return float64(typedState.Sum), int(typedState.NAdds)
	case AvgState:
		return typedState.Value, 1
	default:
		fmt.Printf("[aggregateProcessStateHelper]Unsupported state type: %T. Maybe a map state inside a map state?\n", currState)
	}
	return
}

