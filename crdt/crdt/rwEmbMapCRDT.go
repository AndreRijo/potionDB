func CheckInnerForVariablesMap(args map[string]ReadArguments, pointer interface{}) {
	for _, args := range args {
		if args.HasVariables() {
			args.(ReadArgumentsWithInner).CheckInnerForVariables(pointer)
		}
	}
}

func CheckInnerForVariablesSingle(args ReadArguments, pointer interface{}) {
	if args.HasVariables() {
		args.(ReadArgumentsWithInner).CheckInnerForVariables(pointer)
	}
}

func CheckInnerForVariablesSingleComparable(args CompareArguments, pointer interface{}) {
	switch typedArgs := args.(type) {
	case IntArgCompareArguments:
		typedArgs.Value = pointer.(*float64)
	case FloatArgCompareArguments:
		typedArgs.Value = pointer.(*float64)
	}
}

func CheckInnerForVariablesMapComparable(args map[string]CompareArguments, pointer interface{}) {
	for _, args := range args {
		CheckInnerForVariablesSingleComparable(args, pointer)
	}
}

func (compArgs GetNoCompareArguments) SatisfiesComp() bool { return true }
func (compArgs IntCompareArguments) SatisfiesComp(otherValue int64) bool {
	switch compArgs.CompType {
	case EQ:
		return compArgs.Value == otherValue
	case NEQ:
		return compArgs.Value != otherValue
	case LEQ:
		return compArgs.Value <= otherValue
	case L:
		return compArgs.Value < otherValue
	case H:
		return compArgs.Value > otherValue
	case HEQ:
		return compArgs.Value >= otherValue
	}
	return true
}
func (compArgs FloatCompareArguments) SatisfiesComp(otherValue float64) bool {
	switch compArgs.CompType {
	case EQ:
		return compArgs.Value == otherValue
	case NEQ:
		return compArgs.Value != otherValue
	case LEQ:
		return compArgs.Value <= otherValue
	case L:
		return compArgs.Value < otherValue
	case H:
		return compArgs.Value > otherValue
	case HEQ:
		return compArgs.Value >= otherValue
	}
	return true
}
func (compArgs StringCompareArguments) SatisfiesComp(otherValue string) bool {
	if compArgs.IsEqualComp {
		return compArgs.Value == otherValue
	}
	return compArgs.Value != otherValue
}
func (compArgs BytesCompareArguments) SatisfiesComp(otherValue []byte) bool {
	if compArgs.IsEqualComp {
		if len(compArgs.Value) != len(otherValue) {
			return false
		}
		for i := range compArgs.Value {
			if compArgs.Value[i] != otherValue[i] {
				return false
			}
		}
		return true
	} //Else: NEQ.
	if len(compArgs.Value) != len(otherValue) { //Different lengths imply different byte slices.
		return true
	}
	for i := range compArgs.Value {
		if compArgs.Value[i] != otherValue[i] {
			return true
		}
	}
	return false
}
func (compArgs BoolCompareArguments) SatisfiesComp(otherValue bool) bool {
	return (compArgs.IsEqualComp && compArgs.Value == otherValue) || (!compArgs.IsEqualComp && compArgs.Value != otherValue)
}

