type markedVC []int64 //The mark is a true/false value represented in the 2nd highest bit.
//We use it to know if a replica has already seen a vc that is higher than markedVC.
//When all replicas have a vc higher than markedVC, markedVC can be safely deleted.

func (v markedVC) isPosMarked(pos int) bool {
	return v[pos]&(1<<62) != 0
}

func (v markedVC) isLowerThan(other []int64) bool { //We only want this to return false if at least one position in v is > than other.
	for i, val := range v {
		if val > other[i] && !v.isPosMarked(i) {
			return false
		}
	}
	return true
}

func (v markedVC) setMark(pos int) {
	v[pos] |= (1 << 62) //Sets the mark bit
}

func (v markedVC) unmark(pos int) {
	v[pos] &= ^(1 << 62) //Unsets the mark bit
}

func (v markedVC) isAllMarked() bool {
	for i := range v {
		if !v.isPosMarked(i) {
			return false
		}
	}
	return true
}

func (v markedVC) clearMarks() {
	for i := range v {
		v.unmark(i)
	}
}

