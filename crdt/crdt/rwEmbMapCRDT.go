func (crdt *RWEmbMapCrdt) applyFirstUpdateLargeLocal(updTs clocksi.Timestamp, upds []EmbMapUpdate) {
	shardedMap := crdt.entries.(tools.ShardedMapWithBitset[CRDT])
	nShards := shardedMap.GetNShards()

	//Two phases:
	//1. Split the updates per shard, according to the hashkey. Prepare CRDTs & apply downstreams (as we have to update the original upds slice with the downstreams.)
	//2. Assign the CRDTs to the map in parallel, with a goroutine per shard (or per few shards, if nShards > runtime.NumCPU())
	//Goroutines of phase 1 will send the CRDTs directly to the goroutines of phase 2, as they finish processing.

	//Preparing variables for phase 1
	nRoutines := min(len(upds)/100000, runtime.NumCPU()) //Ironically this is likely the heavier phase :(
	updsPerRoutine, currStart := len(upds)/nRoutines, 0

	routineShards := min(nShards, tools.Max(nRoutines/2, 1)) //This phase is likely faster than phase 1.
	shardsPerRoutine, remainder := nShards/routineShards, nShards%routineShards
	shareChans := make([]chan ShardedCrdt, routineShards)
	for i := 0; i < routineShards; i++ {
		if i < remainder {
			shareChans[i] = make(chan ShardedCrdt, (shardsPerRoutine+1)*nRoutines) //+1 for the remainder
		} else {
			shareChans[i] = make(chan ShardedCrdt, (shardsPerRoutine)*nRoutines)
		}
	}
	fmt.Printf("[RWEmbMapCRDT]applyFirstUpdateLargeLocal: Upd size %d, nShards %d, 1st/2nd Phase routines: %d/%d, shardsPerRoutine %d, remainder %d.\n", len(upds), nShards, nRoutines, routineShards, shardsPerRoutine, remainder)
	//These goroutines will prepare the CRDTs, apply the downstreams and send the results to the respective shards.
	for i := 0; i < nRoutines-1; i++ {
		go crdt.updLocalShardingHelper(updTs, upds[currStart:currStart+updsPerRoutine], shareChans, nShards, shardsPerRoutine, remainder)
		currStart += updsPerRoutine
	}
	go crdt.updLocalShardingHelper(updTs, upds[currStart:], shareChans, nShards, shardsPerRoutine, remainder)

	//start: i * shardsPerRoutine
	//end: (i+1) * shardsPerRoutine (+1 if i < remainder)
	//Goroutines that will actually assign the CRDTs to the map.
	wg := sync.WaitGroup{}
	wg.Add(routineShards)
	for i := 0; i < routineShards; i++ {
		go crdt.assignShardedCRDTs(shardedMap, shareChans[i], &wg)
	}
	wg.Wait()
	shardedMap.SetInvalidLen()
}

func (crdt *RWEmbMapCrdt) updLocalShardingHelper(updTs clocksi.Timestamp, upds []EmbMapUpdate, shareChans []chan ShardedCrdt, nShards, shardsPerRoutine, remainder int) {
	//Will just use append here. If I don't use append, I need to keep a slice of counts and, on every insert, check it and the len, to ensure I'm not writting out of bounds.
	//Furthermore, I would also need to check the slice (and increment) to assign the value. Too many slice accesses. Better use append and benefit from count locality.
	shardedCrdt := make([][]PairKeyCrdt, nShards)
	initialSize := len(upds)/nShards + len(upds)/(nShards*20)
	for i := 0; i < nShards; i++ {
		shardedCrdt[i] = make([]PairKeyCrdt, 0, initialSize)
	}
	var shard uint64
	var downUpd DownstreamArguments
	for i, keyUpdPair := range upds {
		shard = tools.CalculateShard(keyUpdPair.Key, nShards)
		embCRDT := InitializeCrdt(keyUpdPair.Upd.GetCRDTType(), keyUpdPair.Upd.GetDATAType(), crdt.replicaID)
		downUpd = embCRDT.Update(keyUpdPair.Upd)
		embCRDT.Downstream(updTs, downUpd) //There will never be any generated downstreams as it is new CRDTs (so NuCRDTs will not have anything to undo)
		upds[i].Upd = downUpd
		shardedCrdt[shard] = append(shardedCrdt[shard], PairKeyCrdt{Key: keyUpdPair.Key, Crdt: embCRDT})
		/*if embCRDT == nil {
			fmt.Printf("[RWEmbMapCRDT]updLocalShardingHelper. Nil embCRDT! Upd: %+v (Type: %T). key: %s\n", keyUpdPair.Upd, keyUpdPair.Upd, keyUpdPair.Key)
		}*/
		//embCRDT.(CRDTVM).GC(updTs) //We GC directly, as the idea of first update is to load initial data, so we do not keep history.
	}
	count := shardsPerRoutine
	if remainder > 0 {
		count++
		remainder--
	}
	currChan, chanI := shareChans[0], 0
	counts := make([]int, nShards)
	for i, shardCRDTs := range shardedCrdt { //If we have shardsPerRoutine = 5, remainder = 2 and shards = 82, then [0...5, 6...11, 12...16, 17...21, 22...26, ...]
		currChan <- ShardedCrdt{shard: i, crdts: shardCRDTs}
		counts[chanI]++
		count--
		if count == 0 && i != nShards-1 { //If it's the last one, no need to change chan
			chanI++
			currChan = shareChans[chanI]
			count = shardsPerRoutine
			if remainder > 0 {
				count++
				remainder--
			}
		}
	}
	totalCount := 0
	for _, value := range counts {
		totalCount += value
	}
	//fmt.Printf("[RWEmbMapCRDT]updLocalShardingHelper: Finish. Total count: %v. NShards, nShardRoutines: %d, %d\n", totalCount, nShards, len(shareChans))
}

func (crdt *RWEmbMapCrdt) updRemoteShardingHelper(upds []KeyDownArgsPair, shareChans []chan ShardedUpd, nShards, shardsPerRoutine, remainder int) {
	//Similarly to local, better use append to avoid an extra array of counts and multiple array accesses.
	//Beginning and 2nd part of the code is extremely similar to local's version... but different types make it hard to generalize. :(
	shardedUpds := make([][]KeyDownArgsPair, nShards)
	initialSize := len(upds)/nShards + len(upds)/(nShards*20)
	for i := 0; i < nShards; i++ {
		shardedUpds[i] = make([]KeyDownArgsPair, 0, initialSize)
	}
	var shard uint64
	for _, upd := range upds {
		shard = tools.CalculateShard(upd.Key, nShards)
		shardedUpds[shard] = append(shardedUpds[shard], upd)
	}
	count := shardsPerRoutine
	if remainder > 0 {
		count++
		remainder--
	}
	currChan, shardI := shareChans[0], 0
	for i, shardUpds := range shardedUpds { //If we have shardsPerRoutine = 5, remainder = 2 and shards = 82, then [0...5, 6...11, 12...16, 17...21, 22...26, ...]
		currChan <- ShardedUpd{shard: i, upds: shardUpds}
		count--
		if count == 0 && i != nShards-1 { //If it's the last one, no need to change chan
			shardI++
			currChan = shareChans[shardI]
			count = shardsPerRoutine
			if remainder > 0 {
				count++
				remainder--
			}
		}
	}
}

