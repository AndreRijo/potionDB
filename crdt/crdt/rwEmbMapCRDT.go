func (crdt *RWEmbMapCrdt) Downstream(updTs clocksi.Timestamp, downstreamArgs DownstreamArguments) (otherDownstreamArgs DownstreamArguments) {
	////fmt.Println("Downstreaming:", downstreamArgs)
	//When applying downstreams in the emb CRDTs, new ops may be returned from a NuCRDT
	//crdt.hasUpdsSinceGC = true
	//fmt.Printf("[RWEmbMapCRDT]Downstream. HasUpdsSinceGC set to true.\n")
	if multiUpd, ok := downstreamArgs.(MultiUpd); ok {
		var otherDown MultiUpd
		for _, innerDown := range multiUpd {
			newDown := crdt.Downstream(updTs, innerDown.(DownstreamArguments))
			if newDown != nil {
				otherDown = append(otherDown, newDown)
			}
		}
		/*if len(multiUpd) > 1 {
			fmt.Printf("[RWEmbMapCRDT]MultiUpd with %d updates, downstreamed. Len of map: %d. Type of map: %T\n", len(multiUpd), crdt.entries.Len(), crdt.entries)
		}*/
		if len(otherDown) == 0 {
			return nil
		}
		return otherDown
	}
	effect, otherDownstreamArgs := crdt.applyDownstream(updTs, downstreamArgs, NORMAL)
	//Necessary for inversibleCrdt
	if effect != nil { //We don't want to add firstUpdate to history, as they are intended for initial data.
		crdt.addToHistory(updTs, downstreamArgs, effect)
		crdt.hasUpdsSinceGC = true
	}
	return
}

// Note: When reapplying ops, we need to ensure that we don't replay downstreams in the embedded CRDTs
// Hence the use of the boolean
func (crdt *RWEmbMapCrdt) applyDownstream(updTs clocksi.Timestamp, downstreamArgs DownstreamArguments, isRedo bool) (effect Effect,
	otherDownstreamArgs DownstreamArguments) {
	effect = NoEffect{}
	switch opType := downstreamArgs.(type) {
	case DownstreamRWEmbMapUpdateAll:
		effect, otherDownstreamArgs = crdt.applyUpdateAll(updTs, opType.Upds, opType.RmvEntries, opType.ReplicaID, isRedo)
	case DownstreamRWEmbMapRemoveAll:
		effect = crdt.applyRemoveAll(opType.Rems, opType.ReplicaID, opType.Ts)
	case DownstreamRWEmbMapUpdateAllArray:
		effect, otherDownstreamArgs = crdt.applyUpdateAllArray(updTs, opType.Upds, opType.RmvEntries, opType.ReplicaID, isRedo)
	case DownstreamRWEmbMapUpdateSingle:
		effect, otherDownstreamArgs = crdt.applyUpdateSingle(updTs, opType.Key, opType.Upd, opType.RmvEntries, opType.ReplicaID, isRedo)
	case DownstreamRWEmbMapRemoveSingle:
		effect = crdt.applyRemoveSingle(opType.Rem, opType.ReplicaID, opType.Ts)
	case LocalDownstreamRWEmbMapFirstUpdate:
		//Note: redo is not possible for this update type. Effects are also not supported, as redo is not allowed. Please use DownstreamRWEmbMapUpdateAllArray if redoing is necessary.
		crdt.applyLocalFirstUpdate(updTs, opType.Upds)
		return nil, nil
	case RemoteDownstreamRWEmbMapFirstUpdate:
		//Note: redo is not possible for this update type. Effects are also not supported, as redo is not allowed. Please use DownstreamRWEmbMapUpdateAllArray if redoing is necessary.
		crdt.applyRemoteFirstUpdate(updTs, opType.Upds)
		return nil, nil
	case EmbMapInit:
		//crdt.applyInit(int(opType))
		crdt.applyInit(opType)
		return nil, nil
	default:
		fmt.Printf("[RWEmbMapCRDT][Downstream]Unsupported downstream type %v (%T)\n", downstreamArgs, downstreamArgs)
	}
	return &effect, otherDownstreamArgs
}

func (crdt *RWEmbMapCrdt) applyUpdateAllArray(updTs clocksi.Timestamp, upds []KeyDownArgsPair,
	remClks []int64, remoteID uint16, isRedo bool) (effect RWEmbMapUpdateAllEffect, otherDownstreamArgs DownstreamArguments) {
	effect = RWEmbMapUpdateAllEffect{
		Updated:   make([]string, len(upds)),
		ReplicaID: remoteID,
	}
	newDown := make(map[string]DownstreamArguments) //emb NuCRDTs may generate new downstreams
	updatedIndex := 0

	//TODO: Remove this
	nStringArrays := 0

	//Optimized insertion without checking for removes
	if len(crdt.removes) == 0 {
		//start := time.Now().UnixNano()
		//If the number of new CRDTs is much higher than the existing ones, force a resize
		//Better than having Go do automatically many small resizes
		//This is specially useful when doing initial load of data.
		crdt.resizeMapIfNeeded(len(upds))

		entries := crdt.entries
		//Further optimized insertion
		if !entries.IsNotEmpty() { //If it's empty (!isNotEmpty), we can do a faster loop (as all CRDTs will be new)
			for i, pair := range upds {
				//Store effect, even if it's a redo
				effect.Updated[i] = pair.Key
				if !isRedo {
					// Only apply the upd if it isn't a redo (since if it's a redo, we'll just ask the embedded CRDT to rebuild itself by the end)
					embCRDT := InitializeCrdt(pair.Upd.GetCRDTType(), pair.Upd.GetDATAType(), crdt.replicaID)
					if embCRDT.GetCRDTType() == proto.CRDTType_LWWREG {
						nStringArrays++
					}
					embCRDT.Downstream(updTs, pair.Upd) //No extra downstream will be generated, as it's the first time we create the CRDT (so NuCRDTs will not generate updates).
					entries.Set(pair.Key, embCRDT)
				}
			}
			updatedIndex = len(upds)
			//timeTaken := (time.Now().UnixNano() - start) / 1000000
			//if timeTaken > 10 {
			//	fmt.Printf("[RWEmb][ApplyUpdateAllArray]Optimized insertion took %dms for %d upds.\n", timeTaken, len(upds))
			//}
			if nStringArrays > 100 {
				fmt.Printf("[RWEmb][ApplyUpdateAllArray]Optimized insertion. %d registers have been initialized and downstreamed. Size of crdt.entries: %d\n", nStringArrays, entries.Len())
			}
		} else {
			for i, pair := range upds {
				//Store effect, even if it's a redo
				effect.Updated[i] = pair.Key
				if !isRedo {
					// Only apply the upd if it isn't a redo (since if it's a redo, we'll just ask the embedded CRDT to rebuild itself by the end)
					embCRDT, new := crdt.getOrCreateEmbCrdt(pair.Key, pair.Upd)
					embDownstream := embCRDT.Downstream(updTs, pair.Upd)
					if new {
						entries.Set(pair.Key, embCRDT)
						if embCRDT.GetCRDTType() == proto.CRDTType_LWWREG {
							nStringArrays++
						}
					} else { //Only can happen if CRDT is not new.
						if embDownstream != nil {
							newDown[pair.Key] = embDownstream
						}
					}
				}
			}
			updatedIndex = len(upds)
			if nStringArrays > 100 {
				fmt.Printf("[RWEmb][ApplyUpdateAllArray]Non-optimized insertion. %d registers have been initialized and downstreamed. Size of crdt.entries: %d\n", nStringArrays, crdt.entries.Len())
			}
		}
		crdt.entries = entries
	} else {
		effect.AddedMark = make([]string, 0, len(upds)/2)
		//fmt.Println("[ADD]Applying Add from", remoteID, "with remClks", remClks, "and upds", upds)
		for _, pairUpd := range upds {
			keyRemClk, has := crdt.removes[pairUpd.Key]
			canAdd := !has
			//Remove-wins policy, this add can only have effect if it surparsses all removes.
			if has {
				canAdd = keyRemClk.isLowerThan(remClks) //remClks must be >= in all positions for the add to be applicable.
				if canAdd {                             //Safe to add, as this add is after the remove. We need to add the mark
					keyRemClk.setMark(int(remoteID))
					effect.AddedMark = append(effect.AddedMark, pairUpd.Key)
					if keyRemClk.isAllMarked() {
						if effect.PreviousRmvClk == nil {
							effect.PreviousRmvClk = make(map[string]markedVC)
						}
						effect.PreviousRmvClk[pairUpd.Key] = keyRemClk
						delete(crdt.removes, pairUpd.Key)
					}
				}
			}

			if canAdd { //Actually applying the add
				//Store effect, even if it's a redo
				effect.Updated[updatedIndex] = pairUpd.Key
				updatedIndex++
				if !isRedo { //Only apply the upd if it isn't a redo (since if it's a redo, we'll just ask the embedded CRDT to rebuild itself by the end)
					embCRDT, new := crdt.getOrCreateEmbCrdt(pairUpd.Key, pairUpd.Upd)
					embDownstream := embCRDT.Downstream(updTs, pairUpd.Upd)
					if new {
						////fmt.Println("Storing new emb CRDT")
						//fmt.Println("[ADD]Created new CRDT")
						crdt.entries.Set(pairUpd.Key, embCRDT)
					}
					if embDownstream != nil {
						//fmt.Println("[ADD]Embedded generated new downstreams")
						newDown[pairUpd.Key] = embDownstream
					}
				}
			}
		}
	}

	effect.Updated = effect.Updated[:updatedIndex]
	if len(newDown) == 0 {
		//fmt.Println("[ADD]No new downstreams, returning.")
		return effect, nil
	}
	//fmt.Println("[ADD]Got new downstreams!")
	newRmvEntries := make([]int64, clocksi.GetNumberReplicas())
	crdt.rmvClock.FastCopyInto(newRmvEntries)
	return effect, DownstreamRWEmbMapUpdateAll{Upds: newDown, RmvEntries: newRmvEntries, ReplicaID: crdt.sortedReplicaID}
}

func (crdt *RWEmbMapCrdt) resizeMapIfNeeded(updSize int) {
	entriesLen := crdt.entries.Len()
	if (!crdt.hasInitSize || entriesLen > 0) && updSize/100 > entriesLen { //We avoid resizing if we already set an initial size, which could show as len == 0.
		newSize := updSize + entriesLen
		newEntries := crdt.createMap(newSize)
		newEntries.CopyFrom(crdt.entries)
		//fmt.Printf("[RWEmb]Optimized resize (number of upds: %d)\n", updSize)
		fmt.Printf("[RWEmbMap]Optimized resize. Upds: %d. Old type of map: %T. New type of map: %T. Had initial size: %v.\n",
			updSize, crdt.entries, newEntries, crdt.hasInitSize)
		crdt.entries = newEntries
	}
}

