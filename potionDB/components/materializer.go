func getHash(keyParams crdt.KeyParams) (key uint64) {
	if len(keyParams.Key)+len(keyParams.Bucket) < 64 { //Fast path. <64 to accomodate for the byte of CrdtType
		var buf [64]byte //Should be stack-allocated.
		_ = buf[63]      //To avoid bounds check in copy.
		n := 0
		n += copy(buf[n:], keyParams.Key)
		n += copy(buf[n:], keyParams.Bucket)
		//binary.LittleEndian.PutUint32(buf[n:], uint32(keyParams.CrdtType))
		buf[n] = byte(keyParams.CrdtType) //Faster than using binary package for just one byte.
		return hashFunc.Hash(buf[:n+1])
		//return hashFunc.Hash(buf[:n+4])
	} else { //Slower path for longer keys.
		buf, n := make([]byte, len(keyParams.Key)+len(keyParams.Bucket)+1), 0
		_ = buf[len(buf)-1] //To avoid bounds check in copy.
		n += copy(buf[n:], keyParams.Key)
		n += copy(buf[n:], keyParams.Bucket)
		buf[n] = byte(keyParams.CrdtType) //Faster than using binary package for just one byte.
		//binary.LittleEndian.PutUint32(buf[n:], uint32(keyParams.CrdtType))
		return hashFunc.Hash(buf)
	}
}

