const (
	CLEAN_PREP_SLICE_FACTOR = 0.5 //For prepClockSlice, we'll shift left the elements when half of the slice is marked as removed.
)

type prepClockSlice struct {
	slice                  []TxnIdClkPair
	removed                tools.BitSet
	nRemoved, lastNRemoved int
	nextWritePos           int   //points to the position after the last position written (which may be higher than the "visible len", as we do lazy removals.)
	firstPos               int   //Position with the min (mins are at the head, so it'll be 0 until a remove is applied.)
	partID                 int16 //Debug purposes
	//prepLog                tools.SliceWithCounter[MatLogInfo] //Tmp, for debug
}

func (pc *prepClockSlice) New(size int) (newPc prepClockSlice) {
	pc.slice = make([]TxnIdClkPair, size)
	pc.removed = tools.NewGrowableBitSet(size)
	return *pc
}

func (pc *prepClockSlice) SetPartID(partID int16) {
	pc.partID = partID
}

// Always at the end.
func (pc *prepClockSlice) Append(value TxnIdClkPair) {
	if pc.nextWritePos == len(pc.slice) {
		pc.slice = append(pc.slice, value)
		pc.slice = pc.slice[:cap(pc.slice)] //Extending to capacity
	} else {
		pc.slice[pc.nextWritePos] = value
	}
	pc.nextWritePos++
}

func (pc *prepClockSlice) PeekMin() TxnIdClkPair {
	return pc.slice[pc.firstPos]
}

