// - Frequent check of min and max;
// - Frequent removal of any position, with a known element (albeit slightly less frequent than check), with a tendency to remove smaller elements.
// - Appends are always at the tail.
// - Thus, we keep a partially sorted slice: keep a few mins, and a few maxs. When one of them gets empty, we search and refill (rare).
// - Removes are usually efficient: if we get lucky that the removed position is unchanged, the removal is O(1). If it was removed, we search (O(n)), but avoid shift.
