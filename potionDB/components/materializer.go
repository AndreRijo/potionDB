func (pc *prepClockSlice) Len() int {
	return pc.nextWritePos - pc.nRemoved
}

func (pc *prepClockSlice) IsEmpty() bool {
	return pc.Len() == 0
}

func (pc *prepClockSlice) GetLastPos() int {
	return pc.nextWritePos - 1
}

func (pc *prepClockSlice) Remove(index int, element TxnIdClkPair) {
	index = tools.Min(index, pc.nextWritePos-1) //We may have other removals before and have less elements now. Skip removed elements.
	if pc.nextWritePos <= 20 {
		//if pc.nextWritePos <= 1000 {
		pc.removeNotLazy(index, element)
		return
	}
	//panic(fmt.Sprintf("[PCS%d]Too many elements in prepClockSlice. Contents: %v.\n", pc.partID, pc.slice[:pc.nextWritePos]))
	//fmt.Printf("[PCS%d] Lazy remove of element with txnId %d at index %d. FirstPos: %d. NextWritePos: %d. NRemoved: %d. Slice: %v\n", pc.partID, element.txnId, index, pc.firstPos, pc.nextWritePos, pc.nRemoved, pc.slice[:pc.nextWritePos])
	posRemoved := index
	if pc.slice[index].txnId == element.txnId { //Expected path.
		pc.removed.Set(index)
		pc.nRemoved++
	} else { //This case will happen when shifts occour. Note that the element must always be to the left of index.
		posRemoved = -1
		if pc.lastNRemoved < 100 || index < pc.lastNRemoved { //Heuristics. The idea is that in this case not many elements, so the shift won't also be very big, so we just iterate normally.
			for i := index - 1; i >= 0; i-- {
				if pc.slice[i].txnId == element.txnId {
					posRemoved = i
					break
				}
			}
			if posRemoved == -1 {
				panic(fmt.Sprintf("[PCS%d]Element with txnId %d, pos %d, not found for removal in prepClockSlice, direct iteration. FirstPos: %d. NextWritePos: %d. NRemoved: %d. Slice: %v. Bitset: %v\n", pc.partID, element.txnId, index, pc.firstPos, pc.nextWritePos, pc.nRemoved, pc.slice[:pc.nextWritePos], pc.removed.ToString()))
			}
		} else { //Do a skip. We may have to search in either direction afterwards, we find this out by comparing the clock once.
			//oldSize := int(float64(pc.lastNRemoved) * CLEAN_PREP_SLICE_FACTOR)
			newIndex := int(float64(index) * CLEAN_PREP_SLICE_FACTOR) //Idea: the more to the left the element is, the less positions we skip. Skip is proportional to the clean factor.
			currEntry := pc.slice[newIndex]
			if currEntry.txnId == element.txnId { //We got lucky and found the element right away.
				posRemoved = newIndex
			} else {
				//if currEntry.clk.IsHigher(element.clk) { //OK, we have to keep going left.
				if currEntry.clk.GetPos(shared.SortedReplicaID) > element.clk.GetPos(shared.SortedReplicaID) {
					for i := newIndex - 1; i >= 0; i-- {
						if pc.slice[i].txnId == element.txnId {
							posRemoved = i
							break
						}
					}
				} else {
					for i := newIndex + 1; i < pc.nextWritePos; i++ {
						if pc.slice[i].txnId == element.txnId {
							posRemoved = i
							break
						}
					}
				}
			}
			if posRemoved == -1 {
				panic(fmt.Sprintf("[PCS%d]Element with txnId %d, pos %d, not found for removal in prepClockSlice, skip search. FirstPos: %d. NextWritePos: %d. NRemoved: %d. Slice: %v. Bitset: %v\n", pc.partID, element.txnId, index, pc.firstPos, pc.nextWritePos, pc.nRemoved, pc.slice[:pc.nextWritePos], pc.removed.ToString()))
			}
			//compClk := pc.slice[newIndex].clk.Compare(element.clk)
		}
		pc.removed.Set(posRemoved)
		pc.nRemoved++
		if pc.slice[posRemoved].txnId != element.txnId {
			panic(fmt.Sprintf("[PCS%d]Lazy remove: tried to remove txnId %d, but it wasn't found! Removing pos %d, which has txnId %d. Clk to remove: %s. Clk being removed: %s.\n", pc.partID, element.txnId, posRemoved, pc.slice[posRemoved].txnId, element.clk.ToString(), pc.slice[posRemoved].clk.ToString()))
		}
	}
	//TODO: Remove this check
	if !pc.slice[posRemoved].clk.IsEqual(element.clk) {
		panic(fmt.Sprintf("[PCS%d]Lazy remove: tried to remove txnId %d, but the clocks don't match! Removing pos %d, which has txnId %d. Clk to remove: %s. Clk being removed: %s.\n", pc.partID, element.txnId, posRemoved, pc.slice[posRemoved].txnId, element.clk.ToString(), pc.slice[posRemoved].clk.ToString()))
	}
	if posRemoved == pc.nextWritePos-1 { //We removed the last element, we can just move the pointer back.
		for ; pc.removed.GetBit(posRemoved); posRemoved-- { //Keep skipping until we find a non-empty position. Remove everything on the way that is empty.
			pc.removed.Unset(posRemoved)
			pc.nRemoved--
		}
		pc.nextWritePos = posRemoved + 1
	} else if posRemoved == pc.firstPos { //We removed the min, we need to update it. We know for sure there's at least one element as (as posRemoved is not equal to the lastPos)
		for posRemoved = posRemoved + 1; pc.removed.GetBit(posRemoved); posRemoved++ { //Keep skipping until we find a non-empty position.
		}
		pc.firstPos = posRemoved
	}
	//Number of tombstones > nextWritePos * 0.5 || less than 20 elements (not really, rather the next position to write is below 20)
	//What we would like would be something as:
	//- The number of removed elements is higher than the number of elements (depending on factor)
	//- When the number of elements is too few (<15?), or the nextWritePos is <= 20, force a shift.
	//    - Don't force a shift as soon as we have <= 20 elements (if nextWritePos is > 20), as maybe later we'll add and remove right away.
	//Since pc.nRemoved keeps track of all removed, then this will account also for situations where both firstPos and nextWritePos are many positions ahead.
	//
	if float64(pc.nRemoved) > float64(pc.nextWritePos)*CLEAN_PREP_SLICE_FACTOR || pc.nextWritePos <= 20 || (pc.Len() <= 15) { //Have to clean.
		pc.clearRemovedEntries()
	}
}

func (pc *prepClockSlice) clearRemovedEntries() {
	//Removes all tombstones (i.e., lazily removed elements), and shifts left the elements.
	//After this method, the first element will always be at the beginning, and nextWritePos is the len of the slice.
	writeI, readI := 0, 0
	isCurrR := false
	for readI < pc.nextWritePos {
		isCurrR = pc.removed.GetBit(readI)
		for isCurrR { //Advance until we find a non-removed element.
			readI++
			isCurrR = pc.removed.GetBit(readI)
		}
		pc.slice[writeI] = pc.slice[readI]
		writeI++
		readI++
	}
	pc.nextWritePos = writeI
	pc.lastNRemoved, pc.nRemoved, pc.firstPos = pc.nRemoved, 0, 0
	pc.removed.Reset()
}

// Note: for safety, any elements still not removed will stay.
// It forces left shift and clears any hidden positions in the slice.
func (pc *prepClockSlice) DeepClear() {
	pc.clearRemovedEntries()
	for i := pc.nextWritePos; i < cap(pc.slice); i++ {
		pc.slice[i] = TxnIdClkPair{}
	}
}

