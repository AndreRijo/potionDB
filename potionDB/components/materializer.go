//This slice is special, as we have the following access patterns:
//- When consulting the slice, we always need either the min or the max: so, sorted is the way to go.
//- We always add at the end, and it's always >= than any existing value
//- We remove any position, so binary search is handy.
//	- Despite being random, remove is more likely on early positions (pattern: prepare -> commit, so earlier prepares will usually get commited earlier too)
//	- Issue: we remove by transactionID... this forces the usage of a map in several scenarios (i.e., in prepare and comitting).
//	- A sorted slice with map is a disaster: we need to update several positions of the map (i.e., all shifted elements)
//	- So that's a big no.
//	- Solution: return the position of the prep clock to TM, have the TM store it in a re-usable slice (saves allocations, pfew), and then return it.
//		- Avoids map entirely. Perfect.
//		- This means we can also keep the slice only partially sorted (i.e., only on the extremes)
//		- Correctness issue: when we remove something from the slice, we need to fill the hole... this means other indexes will now be wrong.
//			- Since we don't have the map anymore, we can't update it...
//			- An option would be to return the clock and position. If we find the element, we can immediately delete it. If not, we search for it.
//			- Nice but...
//				- If with a sorted slice, in practice we're always gonna have to search.
//				- If partially sorted slice, it's problematic when we update the sorted part.
//					- But maybe can still go around this.
//					- Let's try. Seems like it's gonna be complicated, gosh.
//					- Maybe just always do binary search + full sorted slice? But man, the shifts...
//- Consulting is a bit more frequent than removing, but not much (2-3x?)

